    def test_intensity_zero_at_prime(self, gv: dict) -> None:
        for case in gv["pool"]["at_prime"]:
            got = pool_at_prime(case["prime_seed"], case["biome"])
            assert got.intensity == 0
            assert got.rotation_bias == 0


