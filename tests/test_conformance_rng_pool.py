# ── Pool: step_sequences ──────────────────────────────────────────────────────

class TestPoolStepSequences:
    """pool.step_sequences — verify each individual step transition, not just the end state."""

    def test_all_step_transitions(self, gv: dict) -> None:
        for seq in gv["pool"]["step_sequences"]:
            prime_seed = seq["prime_seed"]
            biome = seq["biome"]
            p = pool_at_prime(prime_seed, biome)
            for step_case in seq["steps"]:
                step_n = step_case["step"]
                dir_int = step_case["dir_int"]
                pool_step(p, prime_seed, dir_int)
                label = (
                    f"step_seq prime_seed={prime_seed} biome={biome} "
                    f"step={step_n} dir={step_case['dir']}({dir_int})"
                )
                _assert_pool_eq(p, step_case["pool"], label)

    def test_direction_encoding(self, gv: dict) -> None:
        """dir_int in JSON must match the Python POOL_DIR_* constants."""
        for seq in gv["pool"]["step_sequences"]:
            for step_case in seq["steps"]:
                assert _DIR_MAP[step_case["dir"]] == step_case["dir_int"], (
                    f"Direction encoding mismatch: {step_case['dir']}={step_case['dir_int']} "
                    f"but POOL_DIR_{step_case['dir']}={_DIR_MAP[step_case['dir']]}"
                )
