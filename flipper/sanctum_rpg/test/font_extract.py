"""font_extract — the Flipper's FontSecondary as C bitmaps, for host shots + tests.

The top-down world screen draws each tile with canvas_draw_str in
FontSecondary, which the firmware maps to u8g2_font_haxrcorp4089_tr
(applications/services/gui/canvas.c). The font lives in the firmware, not the
SDK headers, so the host can't draw it. This decodes it once from the
firmware's vendored u8g2 (lib/u8g2/u8g2_fonts.c, BSD-2) and writes
test/font_secondary.h: one 8x10 cell per printable ASCII char, drawn exactly
where world.c's tile loop puts it (x = cell left, baseline = row 7), with
rows 8..9 holding any descender that spills into the tile below.

    python3 test/font_extract.py <path/to/u8g2_fonts.c> > test/font_secondary.h

Re-run only if the firmware changes the font; the header is checked in.
"""
import codecs
import re
import sys

NAME = "u8g2_font_haxrcorp4089_tr"


def load(path):
    lines = open(path, encoding="latin-1").read().split("\n")
    i = next(k for k, l in enumerate(lines) if NAME + "[" in l)
    body = []
    for l in lines[i + 1:]:
        body += re.findall(r'"((?:[^"\\]|\\.)*)"', l)
        if l.rstrip().endswith(";"):
            break
    return codecs.escape_decode("".join(body).encode("latin-1"))[0]


class Bits:
    """u8g2 glyph bitstream: LSB-first within each byte."""

    def __init__(self, data, pos):
        self.d, self.p, self.b = data, pos, 0

    def get(self, n):
        v = 0
        for k in range(n):
            v |= ((self.d[self.p] >> self.b) & 1) << k
            self.b += 1
            if self.b == 8:
                self.b, self.p = 0, self.p + 1
        return v

    def sget(self, n):
        return self.get(n) - (1 << (n - 1))


def glyphs(f):
    """u8g2 font format: 23-byte header, then (encoding, jump, RLE bitmap) records."""
    b0, b1, bw, bh, bx, by, bd = f[2], f[3], f[4], f[5], f[6], f[7], f[8]
    out, p = {}, 23
    while p < len(f) and f[p] != 0:
        enc, jump = f[p], f[p + 1]
        r = Bits(f, p + 2)
        w, h = r.get(bw), r.get(bh)
        x, y = r.sget(bx), r.sget(by)
        r.sget(bd)
        px = []
        while len(px) < w * h:
            zeros, ones = r.get(b0), r.get(b1)
            while True:
                px += [0] * zeros + [1] * ones
                if r.get(1) == 0:
                    break
        out[chr(enc)] = (w, h, x, y, [px[k * w:(k + 1) * w] for k in range(h)])
        p += jump
    return out


def cell(g):
    """10 rows x 8 cols; bbox left at x, bbox bottom at baseline(7) - y."""
    c = [[0] * 8 for _ in range(10)]
    if g is None:
        return c
    w, h, x, y, rows = g
    top = 7 - (h + y) + 1
    for j, row in enumerate(rows):
        for i, v in enumerate(row):
            X, Y = x + i, top + j
            if v and 0 <= X < 8 and 0 <= Y < 10:
                c[Y][X] = 1
    return c


def main():
    G = glyphs(load(sys.argv[1]))
    print("/* font_secondary.h — GENERATED by test/font_extract.py; do not edit.")
    print(" *")
    print(f" * {NAME} (the firmware's FontSecondary), from the Flipper firmware's")
    print(" * vendored u8g2 (lib/u8g2/u8g2_fonts.c, BSD-2-Clause, olikraus/u8g2).")
    print(" * FONT2_CELL[c - 32][row]: an 8-wide x 10-row cell, bit i = column i")
    print(" * (LSB-first, like XBM). Baseline is row 7, as in the world screen's tile")
    print(" * loop; rows 8..9 are a descender drawn into the tile below. Host only. */")
    print("#pragma once")
    print("#include <stdint.h>")
    print("#define FONT2_ROWS 10")
    print("static const uint8_t FONT2_CELL[95][FONT2_ROWS] = {")
    for code in range(32, 127):
        c = cell(G.get(chr(code)))
        bytes_ = [sum(v << i for i, v in enumerate(r)) for r in c]
        label = chr(code).replace("\\", "backslash")
        print("    {" + ", ".join(f"0x{b:02X}" for b in bytes_) + f"}}, /* {label} */")
    print("};")


if __name__ == "__main__":
    main()
